#!/usr/bin/env python3
"""Bundle data/words.json + data/sentences.json (+ grammar, stories) into app/data.js so the app works from file://
and offline without fetch(). Run after every change to the JSON files (npm run build does this and
stamps the cache version, D-032):
    python3 tools/build_data.py
    python3 tools/build_data.py --check    # exit 1 when app/data.js is not what the JSON files give (npm test)
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import audio_lib as A
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
words = json.load(open(os.path.join(root, 'data/words.json'), encoding='utf-8'))
sentences = json.load(open(os.path.join(root, 'data/sentences.json'), encoding='utf-8'))
grammar = json.load(open(os.path.join(root, 'data/grammar.json'), encoding='utf-8'))
stories_path = os.path.join(root, 'data/stories.json')   # reading stories (D-026), checked by tools/validate_stories.py
stories = json.load(open(stories_path, encoding='utf-8')) if os.path.exists(stories_path) else []
# audio (D-005): `au` is the clip key of the spoken text (app/audio/<voice>/<key[:2]>/<key>.mp3, both voices);
# a story title or paragraph gets segments [from, to, voice k|b, key, [[start ms, from, to], ...]] with
# offsets into its `bg`, the word timings coming from data/audio.json once the clips are generated
overrides, cast = A.load('audio_overrides.json'), A.load('cast.json')
timings = json.load(open(A.MANIFEST, encoding='utf-8'))['clips'] if os.path.exists(A.MANIFEST) else {}


def segs(bg, speakers):
    out = []
    for a, b, voice in A.segments(bg, speakers, cast):
        key = A.clip_key(bg[a:b])
        words = [[ms, a + x, a + y] for ms, x, y in timings.get(f'{voice}/{key}', {}).get('w', [])]
        out.append([a, b, A.LETTER[voice], key, words])
    return out


slim_words = [{'rank': w['rank'], 'bg': w['bg'], 'en': w['en'], 'pos': w['pos'], 'cat': w.get('cat', ''), 'forms': w['forms'],
               'learned': w['learned'], 'au': A.clip_key(A.spoken('w:%d' % w['rank'], w['bg'], overrides))}
              for w in words]   # cat: the deck's topic, for sneak-peek distractors (D-031)
sentences = [dict(s, au=A.clip_key(A.spoken('s:' + s['id'], s['bg'], overrides)), **({'au_nl': A.clip_key(s['nl'])} if s.get('nl') else {}))
             for s in sentences]   # au_nl: the Dutch prompt of hands-free listening (D-034)
stories = [dict(st, title=dict(st['title'], au=segs(st['title']['bg'], [])),
                paragraphs=[dict(p, au=segs(p['bg'], p.get('speakers', []))) for p in st['paragraphs']]) for st in stories]
learned = max((w['rank'] for w in words if w['learned']), default=0)
out = os.path.join(root, 'app/data.js')
text = ('// generated by tools/build_data.py — do not edit\n'
        + 'window.TRAKIA_DATA = ' + json.dumps({'words': slim_words, 'sentences': sentences, 'grammar': grammar,
          'stories': stories, 'learnedRank': learned}, ensure_ascii=False, separators=(',', ':')) + ';\n')
if '--check' in sys.argv:
    fresh = os.path.exists(out) and open(out, encoding='utf-8').read() == text
    print('app/data.js is up to date' if fresh else 'app/data.js is stale: run npm run build')
    sys.exit(0 if fresh else 1)
with open(out, 'w', encoding='utf-8') as fh:
    fh.write(text)
print(f'{len(slim_words)} words, {len(sentences)} sentences, {len(grammar["cards"])} grammar cards, {len(stories)} stories, learnedRank={learned} -> {out} '
      f'({os.path.getsize(out)//1024} KB)')
